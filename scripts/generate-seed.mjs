// Builds supabase/seed.sql from the app's own data files, so the database starts
// with exactly the content the prototype shows. Run: npm run db:seed
// The data files stay the source of truth until content moves to the database.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  RA_IDS,
  RA_R,
  RA_COPY,
  RA_LIB,
  RA_TOPIC,
  RA_PLURAL,
} from '../src/features/your-role/data/roles.js';
import { ACA_DEADLINES } from '../src/features/your-role/data/deadlines.js';
import { NEWS, NEWS_FILTERS } from '../src/features/news/data/news.js';
import { ROLES as LIB_ROLES, RES, SHORT } from '../src/features/resource-library/data/resources.js';
import { CHECKLISTS } from '../src/features/checklists/data/checklists.js';

const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  if (Array.isArray(v)) return 'array[' + v.map(q).join(', ') + ']::text[]';
  return "'" + String(v).replace(/'/g, "''") + "'";
};
const row = (vals) => '(' + vals.map(q).join(', ') + ')';
const insert = (table, cols, rows) =>
  rows.length
    ? `insert into public.${table} (${cols.join(', ')}) values\n  ${rows.map(row).join(',\n  ')};\n`
    : '';

const out = [
  '-- Generated by scripts/generate-seed.mjs from src/features/*/data. Do not edit by hand.',
  '-- Content only: no people, profiles or events.',
  '',
];

// Library roles ('all' is a UI option, not a role).
out.push(
  insert(
    'library_roles',
    ['id', 'label', 'short_label', 'lead', 'intro', 'sort_order'],
    LIB_ROLES.filter((r) => r.id !== 'all').map((r, i) => [
      r.id,
      r.label,
      SHORT[r.id],
      r.lead,
      r.intro,
      i + 1,
    ]),
  ),
);

// Roles, criteria, actions.
out.push(
  insert(
    'roles',
    [
      'id',
      'sort_order',
      'library_role',
      'name_en',
      'name_fr',
      'blurb_en',
      'blurb_fr',
      'plural_en',
      'plural_fr',
      'deadline_2027_en',
      'deadline_2027_fr',
      'deadline_2028_en',
      'deadline_2028_fr',
      'note_en',
      'note_fr',
    ],
    RA_IDS.map((id, i) => {
      const e = RA_R[id].en,
        f = RA_R[id].fr;
      return [
        id,
        i + 1,
        RA_LIB[id],
        e.name,
        f.name,
        e.blurb,
        f.blurb,
        RA_PLURAL.en[id],
        RA_PLURAL.fr[id],
        e.d27,
        f.d27,
        e.d28,
        f.d28,
        e.note,
        f.note,
      ];
    }),
  ),
);

out.push(
  insert(
    'role_criteria',
    [
      'role_id',
      'position',
      'tag',
      'title_en',
      'title_fr',
      'summary_en',
      'summary_fr',
      'detail_en',
      'detail_fr',
    ],
    RA_IDS.flatMap((id) =>
      RA_R[id].en.items.map((it, i) => {
        const fr = RA_R[id].fr.items[i];
        return [id, i + 1, it[1] || null, it[0], fr[0], it[2], fr[2], it[3], fr[3]];
      }),
    ),
  ),
);

const actionCols = [
  'role_id',
  'kind',
  'title_en',
  'title_fr',
  'summary_en',
  'summary_fr',
  'button_en',
  'button_fr',
  'intro_en',
  'intro_fr',
  'steps_en',
  'steps_fr',
  'copy_heading_en',
  'copy_heading_fr',
  'copy_button_en',
  'copy_button_fr',
  'copy_text_en',
  'copy_text_fr',
  'done_button_en',
  'done_button_fr',
  'done_title_en',
  'done_title_fr',
  'done_body_en',
  'done_body_fr',
  'done_next_en',
  'done_next_fr',
];
const actions = RA_IDS.flatMap((id) => {
  const e = RA_R[id].en,
    f = RA_R[id].fr,
    copy = RA_COPY[id] || {};
  return [
    [
      id,
      'do',
      e.doTitle,
      f.doTitle,
      e.doSub,
      f.doSub,
      e.doBtn,
      f.doBtn,
      e.act.intro,
      f.act.intro,
      e.act.steps,
      f.act.steps,
      e.act.copyHeading ?? null,
      f.act.copyHeading ?? null,
      e.act.copyBtn ?? null,
      f.act.copyBtn ?? null,
      copy.en ?? null,
      copy.fr ?? null,
      e.act.doneBtn,
      f.act.doneBtn,
      e.done.title,
      f.done.title,
      e.done.body,
      f.done.body,
      e.done.next,
      f.done.next,
    ],
    [
      id,
      'next',
      e.nx.title,
      f.nx.title,
      e.nx.sub,
      f.nx.sub,
      e.nx.btn,
      f.nx.btn,
      e.nx.intro,
      f.nx.intro,
      e.nx.steps,
      f.nx.steps,
      null,
      null,
      null,
      null,
      null,
      null,
      e.nx.doneBtn,
      f.nx.doneBtn,
      e.nx.doneTitle,
      f.nx.doneTitle,
      e.nx.doneBody,
      f.nx.doneBody,
      null,
      null,
    ],
  ];
});
out.push(insert('role_actions', actionCols, actions));

out.push(
  insert(
    'deadlines',
    ['id', 'due_on', 'label_en', 'label_fr'],
    [
      ['y2027', ACA_DEADLINES.y2027, '5 Dec 2027', '5 déc. 2027'],
      ['y2028', ACA_DEADLINES.y2028, '5 Dec 2028', '5 déc. 2028'],
    ],
  ),
);

// News.
const topics = NEWS_FILTERS.filter((f) => f.id !== 'all');
out.push(
  insert(
    'news_topics',
    ['id', 'label', 'sort_order'],
    topics.map((t, i) => [t.id, t.label, i + 1]),
  ),
);
out.push(
  insert(
    'topic_roles',
    ['topic_id', 'role_id'],
    Object.entries(RA_TOPIC).flatMap(([topic, roles]) => roles.map((r) => [topic, r])),
  ),
);
out.push(
  insert(
    'news_items',
    [
      'published_on',
      'date_label',
      'topic_id',
      'tag',
      'title',
      'body',
      'means_lead',
      'means',
      'sources_label',
    ],
    NEWS.map((n) => [
      n.date,
      n.label,
      n.topic,
      n.tag,
      n.title,
      n.body,
      n.meansLead,
      n.means,
      n.sourcesLabel,
    ]),
  ),
);
const src = NEWS.flatMap((n) =>
  n.sources.map(
    (s, i) =>
      `((select id from public.news_items where title = ${q(n.title)}), ${i + 1}, ${q(s.label)}, ${q(s.href)})`,
  ),
);
out.push(
  `insert into public.news_sources (news_id, position, label, url) values\n  ${src.join(',\n  ')};\n`,
);

// Resource library.
out.push(
  insert(
    'resource_groups',
    ['name', 'sort_order'],
    RES.map((g, i) => [g.g, i + 1]),
  ),
);
const res = RES.flatMap((g) =>
  g.items.map(
    (it, i) =>
      `((select id from public.resource_groups where name = ${q(g.g)}), ${i + 1}, ${q(it[0])}, ${q(it[1])}, ${q(it[2])})`,
  ),
);
out.push(
  `insert into public.resources (group_id, position, title, url, description) values\n  ${res.join(',\n  ')};\n`,
);
const resRoles = RES.flatMap((g) =>
  g.items.flatMap((it, i) =>
    it[3].map(
      (r) =>
        `((select r.id from public.resources r join public.resource_groups g on g.id = r.group_id where g.name = ${q(g.g)} and r.position = ${i + 1}), ${q(r)})`,
    ),
  ),
);
out.push(
  `insert into public.resource_roles (resource_id, library_role_id) values\n  ${resRoles.join(',\n  ')};\n`,
);

// Checklists.
out.push(
  insert(
    'checklists',
    ['id', 'title', 'sort_order'],
    CHECKLISTS.map((c, i) => [c.id, c.title, i + 1]),
  ),
);
out.push(
  insert(
    'checklist_items',
    ['id', 'checklist_id', 'position', 'text'],
    CHECKLISTS.flatMap((c) => c.items.map((it, i) => [it.id, c.id, i + 1, it.text])),
  ),
);
out.push(
  insert(
    'checklist_item_refs',
    ['item_id', 'position', 'ref', 'is_en_clause'],
    CHECKLISTS.flatMap((c) =>
      c.items.flatMap((it) => it.refs.map((r, i) => [it.id, i + 1, r.text, !!r.en])),
    ),
  ),
);

const target = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url));
writeFileSync(target, out.join('\n'));
console.log('Wrote', target);
